/**
 * A permanent background behind the whole journal (`quest-list`, the "Journal" block under the
 * tech/civic buttons on the left of the HUD): a gold frame with concave cut-in corners over either
 * the game's hover gradient or, as the alternative, solid navy.
 *
 * ⚠️ TWO PSEUDO-ELEMENTS, the game's own `.highlight-row::before` pattern (default.css): `::before`
 * holds the fill and takes the slider as `opacity`, `::after` holds the frame at full strength.
 * `opacity` on the container itself would fade the journal's text with it.
 *
 * ⚠️ THE SHAPE IS THIS MOD'S OWN PNG (texture/, generated by tools/make-textures.py), served
 * through `fs://game/<mod-id>/…` and registered in `<ImportFiles>`. An SVG `data:` URI draws
 * nothing in this engine, and no game texture has this corner.
 *
 * ⚠️ A RULE IN THE DOCUMENT, not a style on the element: `quest-list` is placed four times in
 * root-game.html (one per HUD layout) and is rebuilt with the HUD. Rewriting the `<style>`
 * element's text makes a change live. Targeted by element name and the component's own
 * `.quest-item-container` (looked up with MustGetElement), never by Tailwind utility classes.
 */

import {
    JournalBackgroundChangedEventName,
    isSolidBackground,
    journalOpacityPercent,
} from './options/journal-background-options.js';

const TEXTURE_ROOT = "fs://game/journal-background/texture";
const FRAME_URL = `${TEXTURE_ROOT}/journal-frame.png`;
const FILL_GRADIENT_URL = `${TEXTURE_ROOT}/journal-fill-gradient.png`;
const FILL_NAVY_URL = `${TEXTURE_ROOT}/journal-fill-navy.png`;

/**
 * ⚠️ `SLICE` MUST MATCH tools/make-textures.py. `CORNER` is how large one 48 px corner is drawn;
 * the notch and the line width scale with it.
 */
const SLICE = 48;
const CORNER = "1.3333333333rem";

/**
 * ⚠️ The padding is paired with an equal negative margin, so the text stays where the game put it
 * and only the background grows outward - except on the LEFT, where the margin is positive: mirrored
 * there, the frame ran into the collapse (minus) button beside the journal.
 */
const PAD_Y = "0.6666666667rem";
const PAD_X = "0.8888888889rem";
const LEFT_GAP = "0.4444444444rem";
/**
 * ⚠️ PAD_X MINUS the game's `pr-3` (0.6666666667rem) on `.quest-item-list`: that padding already
 * sits inside the right edge, and without subtracting it a hovered entry's frame had a visibly
 * wider gap to the right of it than to the left.
 */
const PAD_RIGHT = "0.2222222222rem";
/**
 * ⚠️ Less than PAD_Y on purpose: with the full negative margin the frame's top edge touched the
 * turn/progress counters under the buttons above. The journal moves down by the difference.
 */
const TOP_PULL = "0.1666666667rem";
/**
 * The game's `.quest-item-container` max-heights (quest-list.css), each raised by the vertical
 * padding above.
 *
 * ⚠️ MEASURED 2026-09-29 at 1920x1080 (the small-height rule applies there): without this the
 * container stayed at 275 px while its fxs-scrollable ran 24 px past the frame's bottom edge - the
 * list is sized from the max-height alone, not from what the padding leaves - so a hovered entry
 * at the bottom was drawn outside the frame. Keep in step with PAD_Y and with quest-list.css.
 *
 * ⚠️ THE RAISED MAX-HEIGHT ALONE WAS NOT ENOUGH (2026-10-30): scrolled to the bottom, the last
 * entry's hover gradient still sometimes hung below the frame. The fxs-scrollable is therefore
 * also made a shrinking flex child with `min-height: 0` - a flex item's default `min-height: auto`
 * keeps it at its content's height, so it never shrank to what the title and padding leave.
 */
const MAX_HEIGHT = "34.6666666667rem";          // 33.3333333333rem + 2 x PAD_Y
const MAX_HEIGHT_SMALL = "15.2222222222rem";    // 13.8888888889rem + 2 x PAD_Y
const SMALL_SCREEN_QUERY = "(max-height: 55.5555555556rem)";

/**
 * ⚠️ A hovered/focused entry gets NO FRAME at all (user's instruction, 2026-09-29): neither the
 * game's `hud_list-focus_frame` nor this mod's notched one, which looked wrong nested inside the
 * journal's own frame. The game's hover gradient stays as the highlight, with rounded corners.
 */
const ITEM_RADIUS = "0.4444444444rem";

const styleElement = document.createElement("style");
document.head.appendChild(styleElement);

function borderImage(url) {
    return `
    border-image-source: url("${url}");
    border-image-slice: ${SLICE} fill;
    border-image-width: ${CORNER};`;
}

/**
 * ⚠️ NOTHING IS EMITTED AT 0%, so the slider at zero is exactly the unmodded journal - padding
 * included, which would otherwise shift the text for a background nobody can see.
 */
function apply() {
    try {
        const factor = journalOpacityPercent() / 100;
        if (factor <= 0) {
            styleElement.textContent = "";
            return;
        }
        const fillUrl = isSolidBackground() ? FILL_NAVY_URL : FILL_GRADIENT_URL;
        // ⚠️ `z-index: 0` makes the container a stacking context, so the pseudo-elements' -1 puts
        // them behind its content and not behind the HUD layers around it.
        styleElement.textContent = `
quest-list .quest-item-container {
    z-index: 0;
    padding: ${PAD_Y} ${PAD_RIGHT} ${PAD_Y} ${PAD_X};
    margin: -${TOP_PULL} -${PAD_RIGHT} -${PAD_Y} ${LEFT_GAP};
    max-height: ${MAX_HEIGHT};
}
@media ${SMALL_SCREEN_QUERY} {
    quest-list .quest-item-container {
        max-height: ${MAX_HEIGHT_SMALL};
    }
}
quest-list .quest-item-container fxs-scrollable {
    flex: 1 1 auto;
    min-height: 0;
}
quest-list .quest-item-container::before,
quest-list .quest-item-container::after {
    content: "";
    position: absolute;
    top: 0;
    left: 0;
    right: 0;
    bottom: 0;
    z-index: -1;
    pointer-events: none;
}
quest-list .quest-item-container::before {${borderImage(fillUrl)}
    opacity: ${factor};
}
quest-list .quest-item-container::after {${borderImage(FRAME_URL)}
}
quest-list .quest-list-item-selectable:hover,
quest-list .quest-list-item-selectable:focus,
quest-list .quest-list-item-selectable.pressed {
    border-image-source: none;
    border-radius: ${ITEM_RADIUS};
}
`;
    } catch (error) {
        console.error(`journal-background: the background could not be applied: ${error}`);
    }
}

apply();
window.addEventListener(JournalBackgroundChangedEventName, apply);
console.error("journal-background: loaded");
